'use client';

import React, { createContext, useContext, useState, useEffect } from "react";
import { setUserProperties } from "./analytics";

type Language = "de" | "en" | "pt";

interface LanguageContextProps {
  language: Language;
  setLanguage: (lang: Language) => void;
}

const LanguageContext = createContext<LanguageContextProps>({
  language: "de",
  setLanguage: () => {},
});

export const LanguageProvider = ({ children }: { children: React.ReactNode }) => {
  const [language, setLanguageState] = useState<Language>("de");

  useEffect(() => {
    // On mount, check localStorage or browser language
    const stored = typeof window !== 'undefined' ? localStorage.getItem("lang") : null;
    if (stored === "de" || stored === "en" || stored === "pt") {
      setLanguageState(stored);
    } else {
      const browserLang = (navigator.language || navigator.languages[0] || "de").slice(0,2).toLowerCase();
      if (["de","en","pt"].includes(browserLang)) {
        setLanguageState(browserLang as Language);
      }
    }
  }, []);

  const setLanguage = (lang: Language) => {
    setLanguageState(lang);
    if (typeof window !== 'undefined') {
      localStorage.setItem("lang", lang);
    }
    // Sprache als User-Property an GA melden (no-op falls GA nicht geladen).
    setUserProperties({ language: lang });
  };

  // Beim ersten Mounten die ermittelte Sprache an GA melden, sobald gtag bereit ist.
  useEffect(() => {
    setUserProperties({ language });
  }, [language]);

  return (
    <LanguageContext.Provider value={{ language, setLanguage }}>
      {children}
    </LanguageContext.Provider>
  );
};

export const useLanguage = () => useContext(LanguageContext);

